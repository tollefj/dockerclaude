#!/usr/bin/env bash
# Sandboxed Claude Code in Docker, aligned with "Sikts 10 sikkerhetskrav for agentisk KI" v0.2.

set -euo pipefail

OUT_DIR=".dockerclaude"
# shellcheck source=lib/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib/common.sh"

SIKT_DIR="$ROOT_DIR/sikt"
SIKT_CONFIG="$SIKT_DIR/config"
PIDS_LIMIT=${PIDS_LIMIT:-1024}
MEM_LIMIT=${MEM_LIMIT:-8g}
TOKEN_MOUNT=/root/claude-token
AUDIT_DIR=/opt/audit
MAKE_TARGETS=(dockerclaude dockercheck dockerverify dockeraudit dockerreset dockerterm)

COMPOSE_PROJECT=""
LOG_DIR=""
AGENT_NAME=""
OWNER=""
FIREWALL=0
DOMAINS=()

load_config
load_list HOST_EXEC_PATHS "$CONFIG_DIR/host-exec-paths.txt" "$SIKT_CONFIG/host-exec-paths.txt"
load_list INSTRUCTION_FILE_NAMES "$SIKT_CONFIG/instruction-files.txt"
load_list CICD_PATHS "$SIKT_CONFIG/cicd-paths.txt"
NAMED_VOLUMES+=(audit-sock)

collect_protect_candidates() {
  local path
  for path in "${HOST_EXEC_PATHS[@]}"; do
    [ -e "$path" ] && ! is_hidden "$path" && add_candidate "$path" 1 "host-run"
  done
  while IFS= read -r path; do
    [ -n "$path" ] && ! is_hidden "$path" && add_candidate "$path" 1 "instructions"
  done < <(find_by_name f "${INSTRUCTION_FILE_NAMES[@]}")
  for path in "${CICD_PATHS[@]}"; do
    [ -e "$path" ] && ! is_hidden "$path" && add_candidate "$path" 1 "ci/security"
  done
  if [ "$ISOLATE_GIT" = 0 ] && [ -d .git ]; then
    for path in .git/hooks .git/config; do
      [ -e "$path" ] && add_candidate "$path" 1 "host-run"
    done
  fi
  return 0
}

json_array() {
  local first=1 item
  printf '['
  for item in "$@"; do
    [ "$first" = 1 ] || printf ', '
    first=0
    printf '"%s"' "${item//\"/\\\"}"
  done
  printf ']'
}

write_dockerfile() {
  {
    write_dockerfile_head "$@"
    printf '\nRUN mkdir -p %s /workspace' "$AUDIT_DIR"
    [ "${#OWNED_TARGETS[@]}" -gt 0 ] && printf ' %q' "${OWNED_TARGETS[@]}"
    printf ' && chmod 1777 %s && chown -R node:node /workspace\n\n' "$AUDIT_DIR"
    printf 'COPY entrypoint.sh init-firewall.sh agent-check.sh audit-hook.sh /usr/local/bin/\n'
    printf 'WORKDIR /workspace\n\n'
    printf 'ENTRYPOINT ["/usr/local/bin/entrypoint.sh"]\n'
    printf 'CMD ["claude"]\n'
  } >"$OUT_DIR/Dockerfile"
}

write_compose() {
  local token_source=$1 caps=(SETUID SETGID)
  [ "$FIREWALL" = 1 ] && caps+=(NET_ADMIN NET_RAW)
  [ -n "$token_source" ] && caps+=(DAC_READ_SEARCH)
  {
    printf '# Generated by %s. Run from the project root:\n' "$(basename "$0")"
    printf '#   docker compose -f %s/compose.yml run --rm claude\n' "$OUT_DIR"
    printf 'name: %s\n\nservices:\n' "$COMPOSE_PROJECT"
    printf '  audit:\n    image: %s-agent\n    build: .\n' "$COMPOSE_PROJECT"
    printf '    entrypoint: ["socat", "-u", "UNIX-LISTEN:%s/audit.sock,fork,mode=666,unlink-early", "OPEN:/logs/audit.jsonl,creat,append"]\n' "$AUDIT_DIR"
    printf "    user: '%s:%s'\n" "$(id -u)" "$(id -g)"
    printf '    network_mode: none\n    read_only: true\n'
    printf '    security_opt:\n      - no-new-privileges:true\n    cap_drop:\n      - ALL\n'
    printf '    healthcheck:\n      test: ["CMD-SHELL", "test -S %s/audit.sock"]\n' "$AUDIT_DIR"
    printf '      interval: 1s\n      timeout: 2s\n      retries: 20\n'
    printf '    volumes:\n      - %s\n      - %s\n\n' "$(yaml_quote "audit-sock:$AUDIT_DIR")" "$(yaml_quote "$LOG_DIR:/logs")"
    printf '  claude:\n    image: %s-agent\n    build: .\n' "$COMPOSE_PROJECT"
    printf '    depends_on:\n      audit:\n        condition: service_healthy\n'
    printf '    hostname: %s\n' "$AGENT_NAME"
    printf '    labels:\n      no.sikt.agent.id: %s\n      no.sikt.agent.owner: %s\n' "$(yaml_quote "$AGENT_NAME")" "$(yaml_quote "$OWNER")"
    printf '    init: true\n    working_dir: /workspace\n    stdin_open: true\n    tty: true\n'
    printf '    read_only: true\n    tmpfs:\n      - /tmp:rw,exec,nosuid,nodev,size=2g\n      - /run:rw,noexec,nosuid,nodev,size=16m\n'
    printf '    pids_limit: %s\n    mem_limit: %s\n' "$PIDS_LIMIT" "$MEM_LIMIT"
    printf '    environment:\n'
    printf '      AGENT_ID: %s\n      AGENT_OWNER: %s\n' "$(yaml_quote "$AGENT_NAME")" "$(yaml_quote "$OWNER")"
    printf "      AGENT_FIREWALL: '%s'\n" "$FIREWALL"
    printf "      AGENT_ALLOW_FAIL: '\${AGENT_ALLOW_FAIL:-0}'\n"
    printf "      CLAUDE_CODE_SUBPROCESS_ENV_SCRUB: '1'\n"
    printf '    security_opt:\n      - no-new-privileges:true\n    cap_drop:\n      - ALL\n    cap_add:\n'
    printf '      - %s\n' "${caps[@]}"
    printf '    volumes:\n'
    printf '      - %s\n' "${VOLUME_LINES[@]}"
    printf '\nvolumes:\n'
    printf '  %s:\n' "${NAMED_VOLUMES[@]}"
  } >"$OUT_DIR/compose.yml"
}

write_settings() {
  local mode=$1 memory=$2 hook='{ "type": "command", "command": "/usr/local/bin/audit-hook.sh", "timeout": 10 }'
  local ask_rules=() deny_rules=() memory_flag=false
  load_list ask_rules "$SIKT_CONFIG/ask-rules.txt"
  load_list deny_rules "$SIKT_CONFIG/deny-rules.txt"
  [ "$memory" = 1 ] && memory_flag=true
  # Bash sandbox stays off: bubblewrap needs user namespaces, which Docker's default seccomp profile blocks.
  cat >"$OUT_DIR/managed-settings.json" <<EOF
{
  "permissions": {
    "defaultMode": "$mode",
    "disableBypassPermissionsMode": "disable",
    "ask": $(json_array "${ask_rules[@]}"),
    "deny": $(json_array "${deny_rules[@]}")
  },
  "allowManagedPermissionRulesOnly": true,
  "allowManagedHooksOnly": true,
  "allowManagedMcpServersOnly": true,
  "allowedMcpServers": [],
  "enableAllProjectMcpServers": false,
  "autoMemoryEnabled": $memory_flag,
  "cleanupPeriodDays": 14,
  "sandbox": {
    "enabled": false
  },
  "hooks": {
    "SessionStart": [{ "hooks": [$hook] }],
    "UserPromptSubmit": [{ "hooks": [$hook] }],
    "PreToolUse": [{ "matcher": "*", "hooks": [$hook] }],
    "PostToolUse": [{ "matcher": "*", "hooks": [$hook] }],
    "SessionEnd": [{ "hooks": [$hook] }]
  },
  "env": {
    "DISABLE_TELEMETRY": "1",
    "DISABLE_ERROR_REPORTING": "1",
    "DISABLE_AUTOUPDATER": "1",
    "CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC": "1"
  }
}
EOF
}

install_sikt_files() {
  local file
  for file in entrypoint.sh audit-hook.sh agent-check.sh agent-verify.sh; do
    install_file "$SIKT_DIR/$file" "$file"
  done
  [ -f "$OUT_DIR/prod-endpoints.txt" ] || cp "$SIKT_DIR/prod-endpoints.txt" "$OUT_DIR/prod-endpoints.txt"
}

write_path_lists() {
  local i=0
  {
    printf '# <mode> <path>, hidden from the container. ro masks must stay empty.\n'
    while [ "$i" -lt "${#MASKS[@]}" ]; do
      printf '%s %s\n' "${MASK_MODES[$i]}" "${MASKS[$i]}"
      i=$((i + 1))
    done
  } >"$OUT_DIR/hidden-paths.txt"
  {
    printf '# Paths mounted read-only in the container.\n'
    printf '%s\n' "$OUT_DIR" ${PROTECT[@]+"${PROTECT[@]}"}
    if [ "$PROTECT_PROJECT_CLAUDE" = 1 ]; then printf '.claude\n'; fi
    if [ "$ISOLATE_GIT" = 1 ]; then printf '.git\n'; fi
  } >"$OUT_DIR/protected-paths.txt"
}

write_envelope() {
  local token_source=$1 mode=$2 memory=$3
  local domains_line="unrestricted" git_line="read/write (agent can commit; push has no credentials)"
  [ "$FIREWALL" = 1 ] && domains_line="allowlist: ${DOMAINS[*]}"
  [ "$ISOLATE_GIT" = 1 ] && git_line="read-only (commit and push from the host)"
  {
    printf '# Authority envelope (Sikt agentic AI rule 1, section 5.1)\n'
    printf '# Generated by %s on %s. Verify with: make dockercheck\n\n' "$(basename "$0")" "$(date +%Y-%m-%d)"
    printf 'Identity:      %s (owner: %s)\n' "$AGENT_NAME" "$OWNER"
    printf 'Filesystem:    /workspace = %s, read/write\n' "$PWD"
    printf '               read-only: %s\n' "$(grep -v '^#' "$OUT_DIR/protected-paths.txt" | tr '\n' ' ')"
    printf '               hidden: %s path(s), see hidden-paths.txt\n' "${#MASKS[@]}"
    printf 'Repository:    %s only\n' "$(project_name)"
    printf 'Git:           %s\n' "$git_line"
    if [ -n "$token_source" ]; then
      printf 'Secrets:       model token only (CLAUDE_CODE_OAUTH_TOKEN), scrubbed from subprocesses\n'
    else
      printf 'Secrets:       none (login with /login inside the container)\n'
    fi
    printf 'Network:       %s\n' "$domains_line"
    printf 'Runtime:       docker, read-only root fs, uid node, no capabilities, no-new-privileges, pids<=%s, mem<=%s\n' \
      "$PIDS_LIMIT" "$MEM_LIMIT"
    printf 'Production:    no credentials, no kube/cloud context; probes in prod-endpoints.txt\n'
    printf 'Tools/MCP:     built-in tools only, MCP servers blocked\n'
    printf 'Checkpoints:   permission mode %s, managed ask rules for push/publish/infra/CI edits\n' "$mode"
    printf 'Memory:        %s\n' "$([ "$memory" = 1 ] && echo "auto memory on (make dockerreset deletes it)" || echo "auto memory off")"
    printf 'Audit log:     %s/audit.jsonl (not mounted in the agent container)\n' "$LOG_DIR"
    printf 'Data:          <data classes the agent may handle, e.g. synthetic test data only>\n'
    printf 'Environment:   dev\n'
    printf 'Time:          container removed on exit; token expiry: <token expiry or rotation date>\n'
    printf 'Admin:         none (no root, no sudo, no docker socket)\n'
  } >"$OUT_DIR/authority-envelope.txt"
}

print_make_target() {
  local compose="docker compose -f $OUT_DIR/compose.yml"
  case $1 in
    dockerclaude)
      printf 'dockerclaude: ## Run Claude Code sandboxed in Docker\n'
      printf '\t%s run --build --rm claude; status=$$?; %s down; exit $$status\n\n' "$compose" "$compose" ;;
    dockercheck)
      printf 'dockercheck: ## Run the least-privilege check inside the sandbox\n'
      printf '\t%s run --build --rm claude agent-check.sh; status=$$?; %s down; exit $$status\n\n' "$compose" "$compose" ;;
    dockerverify)
      printf 'dockerverify: ## Scan agent changes on the host (gitleaks, semgrep, osv-scanner)\n'
      printf '\t%s/agent-verify.sh\n\n' "$OUT_DIR" ;;
    dockeraudit)
      printf 'dockeraudit: ## Show the latest agent audit log entries\n'
      printf "\ttail -n 50 '%s/audit.jsonl'\n\n" "$LOG_DIR" ;;
    dockerreset)
      printf 'dockerreset: ## Delete agent memory, login state and container volumes\n'
      printf '\t%s down -v\n\n' "$compose" ;;
    dockerterm)
      printf 'dockerterm: ## Shell into the running dockerclaude container\n'
      printf '\tdocker exec -it -u node $$(docker ps -q --filter label=com.docker.compose.project=%s --filter label=com.docker.compose.service=claude | head -n 1) /bin/bash\n\n' "$COMPOSE_PROJECT" ;;
  esac
}

prompt_network() {
  local package_manager=$1 extra
  echo
  echo "${bold}Network${reset} (rule 1 and 5: egress limited to what the task needs)"
  if confirm "Block network access except an allowlist?" y; then
    FIREWALL=1
    load_list DOMAINS "$SIKT_CONFIG/base-domains.txt"
    [ -f package.json ] && DOMAINS+=(registry.npmjs.org)
    [ "$package_manager" != "${package_manager#yarn@}" ] && DOMAINS+=(repo.yarnpkg.com)
    has_python_project && DOMAINS+=(pypi.org files.pythonhosted.org)
    echo "  Allowed: ${DOMAINS[*]}"
    extra=$(ask "Extra allowed domains (space separated, '@github' for GitHub, '-' for none)" "-")
    # shellcheck disable=SC2206
    [ "$extra" != "-" ] && DOMAINS+=($extra)
  else
    echo "  Network stays unrestricted. agent-check will report R1.9 as WARN."
  fi
  return 0
}

prompt_autonomy() {
  echo
  echo "${bold}Autonomy${reset} (rule 6: critical actions need an explicit checkpoint)"
  echo "  auto: classifier reviews each action. default: ask before edits and commands. acceptEdits: ask before commands."
  echo "  Push, publish, infra CLIs, web access and CI/agent-config edits always ask, in every mode."
  PERMISSION_MODE=$(ask "Permission mode" "auto")
  case "$PERMISSION_MODE" in auto | default | acceptEdits | plan) ;; *)
    echo "  Unknown mode '$PERMISSION_MODE', using default."
    PERMISSION_MODE=default
    ;;
  esac
  MEMORY=0
  confirm "Keep agent auto memory between sessions (rule 8: memory must be reviewable and deletable)?" n && MEMORY=1
  return 0
}

prompt_token() {
  local token_path
  TOKEN_SOURCE=""
  echo
  echo "${bold}Authentication${reset} (rule 3: the only secret in the container is the model token)"
  echo "  Run 'claude setup-token' in another terminal and save the token to a file (e.g. ~/.claude-token)."
  echo "  It is mounted readable by root only and scrubbed from the agent's subprocesses."
  read -r -p "  Press Enter when the token file exists (or to continue without one) " _ || true
  token_path=$(ask "Path to Claude OAuth token file ('-' to skip)" "~/.claude-token")
  [ "$token_path" != "-" ] || return 0
  if [ -r "${token_path/#\~/$HOME}" ]; then
    TOKEN_SOURCE="${token_path/#\~/$HOME}"
  else
    echo "  $token_path is not readable, skipping. Use /login inside Claude instead."
  fi
}

main() {
  if git rev-parse --show-toplevel >/dev/null 2>&1 && [ "$(git rev-parse --show-toplevel)" != "$(pwd -P)" ]; then
    echo "Note: you are not in the git root ($(git rev-parse --show-toplevel))."
    confirm "Continue in $PWD anyway?" n || exit 1
  fi
  command -v docker >/dev/null 2>&1 || echo "Note: docker was not found on PATH."

  if [ -d "$OUT_DIR" ] && [ -n "$(ls -A "$OUT_DIR" 2>/dev/null)" ]; then
    confirm "$OUT_DIR/ already exists. Overwrite?" n || exit 1
  fi

  echo "Scanning $PWD ..."
  collect_secret_candidates
  run_checklist "Paths to hide from the container (rule 3: secrets outside the agent's context)"
  select_masks

  local node_major apk_extra="" package_manager uv_version="" claude_version tag path
  node_major=$(detect_node_major)
  claude_version=$(host_claude_version)
  package_manager=$(detect_package_manager)
  [ -f Makefile ] && apk_extra="make"
  if has_python_project; then
    apk_extra=$(trim "$apk_extra python3")
    uv_version=$(host_uv_version)
  fi

  echo
  echo "${bold}Repository${reset}"
  if [ -d .git ] && confirm "Mount .git read-only (agent cannot commit or install hooks; commit from the host)?" y; then
    ISOLATE_GIT=1
  fi

  reset_candidates
  collect_protect_candidates
  if [ "${#CAND_PATHS[@]}" -gt 0 ]; then
    run_checklist "Paths to mount read-only (rules 6 and 8: host-run config, CI/CD, agent instructions)"
    while IFS=$'\t' read -r tag path; do PROTECT+=("$path"); done < <(selected_candidates)
  fi
  if [ ! -e .claude ] && ! is_hidden .claude; then
    PROTECT_PROJECT_CLAUDE=1
    echo "  .claude/ does not exist yet; an empty read-only one is mounted so the agent cannot create hooks or settings."
  fi

  echo
  echo "${bold}Container${reset}"
  while IFS= read -r path; do NM_DIRS+=("$path"); done < <(find_node_modules)
  if [ "${#NM_DIRS[@]}" -gt 0 ] &&
    ! confirm "Give the container its own empty node_modules (${#NM_DIRS[@]} found; host node_modules is shared otherwise, and macOS binaries won't run on Linux)?" n; then
    NM_DIRS=()
  fi

  prompt_network "$package_manager"
  prompt_autonomy
  prompt_token

  COMPOSE_PROJECT="$(project_name)-claude"
  AGENT_NAME="sikt-agent-$(project_name)-dev"
  OWNER="$(git config user.email 2>/dev/null || true)"
  OWNER="${OWNER:-${USER:-unknown}}"
  LOG_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/dockerclaude/$COMPOSE_PROJECT"
  if [[ "$LOG_DIR" == *:* ]]; then
    echo "Audit log path $LOG_DIR contains ':'. Set XDG_STATE_HOME to a path without it."
    exit 1
  fi
  mkdir -p "$OUT_DIR" "$LOG_DIR"

  build_volumes
  VOLUME_LINES+=("$(yaml_quote "audit-sock:$AUDIT_DIR:ro")")
  VOLUME_LINES+=("$(yaml_quote "./managed-settings.json:/etc/claude-code/managed-settings.json:ro")")
  [ -n "$TOKEN_SOURCE" ] && VOLUME_LINES+=("$(yaml_quote "$TOKEN_SOURCE:$TOKEN_MOUNT:ro")")

  local apk_packages="git bash ripgrep curl jq socat su-exec bind-tools $apk_extra"
  [ "$FIREWALL" = 1 ] && apk_packages+=" iptables ip6tables ipset"

  rm -f "$OUT_DIR/settings.json"
  write_compose "$TOKEN_SOURCE"
  write_dockerfile "$node_major" "$(trim "$apk_packages")" "$package_manager" "$uv_version" "$claude_version"
  write_firewall
  [ "$FIREWALL" = 1 ] && write_allowed_domains "${DOMAINS[@]}"
  write_settings "$PERMISSION_MODE" "$MEMORY"
  install_sikt_files
  write_path_lists
  write_envelope "$TOKEN_SOURCE" "$PERMISSION_MODE" "$MEMORY"

  echo
  setup_makefile

  echo
  echo "${bold}Done.${reset} Wrote $OUT_DIR/ (see $OUT_DIR/authority-envelope.txt for the agent's permissions)"
  echo "Hidden: ${#MASKS[@]} path(s). Read-only: $(grep -vc '^#' "$OUT_DIR/protected-paths.txt") path(s)."
  if [ "$FIREWALL" = 1 ]; then
    echo "Network: allowlist in $OUT_DIR/allowed-domains.txt, cloud metadata blocked."
  else
    echo "Network: unrestricted."
  fi
  echo "Audit log: $LOG_DIR/audit.jsonl"
  echo "Fill in the <placeholders> in $OUT_DIR/authority-envelope.txt and list production hosts in $OUT_DIR/prod-endpoints.txt."
  echo
  echo "Start:    make dockerclaude   (runs agent-check first and refuses to start on FAIL)"
  echo "Check:    make dockercheck"
  echo "Verify:   make dockerverify   (gitleaks, semgrep, osv-scanner on the host before you merge)"
  echo "Upgrade:  docker compose -f $OUT_DIR/compose.yml build --no-cache"
  if [ -n "$TOKEN_SOURCE" ]; then
    echo "Login:    token from $TOKEN_SOURCE is mounted read-only"
  else
    echo "Login:    run /login inside Claude the first time"
  fi
  if [ "${#NM_DIRS[@]}" -gt 0 ]; then
    echo "node_modules starts empty in the container. Install dependencies inside it first."
  fi
}

main "$@"
